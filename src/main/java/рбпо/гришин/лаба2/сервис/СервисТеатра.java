package рбпо.гришин.лаба2.сервис;

import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;
import рбпо.гришин.лаба2.модель.Билет;
import рбпо.гришин.лаба2.модель.Зал;
import рбпо.гришин.лаба2.модель.Показ;
import рбпо.гришин.лаба2.модель.Пользователь;
import рбпо.гришин.лаба2.модель.Спектакль;
import рбпо.гришин.лаба2.репозиторий.РепозиторийТеатра;

import java.time.LocalDateTime;
import java.util.List;

@Service
public class СервисТеатра {
    private final РепозиторийТеатра репозиторий;

    public СервисТеатра(РепозиторийТеатра репозиторий) {
        this.репозиторий = репозиторий;
    }

    // synchronized выполняет операции по очереди: одно место нельзя занять дважды.

    // Спектакли

    public synchronized List<Спектакль> получитьСпектакли() {
        return репозиторий.всеСпектакли();
    }

    public synchronized Спектакль получитьСпектакль(long id) {
        Спектакль спектакль = репозиторий.найтиСпектакль(id);
        if (спектакль == null) {
            throw ошибка(HttpStatus.NOT_FOUND, "Спектакль не найден.");
        }
        return спектакль;
    }

    public synchronized Спектакль создатьСпектакль(Спектакль спектакль) {
        проверитьСпектакль(спектакль);
        спектакль.id = null;
        return репозиторий.сохранитьСпектакль(спектакль);
    }

    public synchronized Спектакль изменитьСпектакль(long id, Спектакль изменения) {
        Спектакль прежний = получитьСпектакль(id);
        Спектакль новый = new Спектакль();
        новый.id = id;
        новый.название = изменения.название != null ? изменения.название : прежний.название;
        новый.длительностьМинут = изменения.длительностьМинут != null
                ? изменения.длительностьМинут : прежний.длительностьМинут;
        новый.возрастноеОграничение = изменения.возрастноеОграничение != null
                ? изменения.возрастноеОграничение : прежний.возрастноеОграничение;
        проверитьСпектакль(новый);
        return репозиторий.сохранитьСпектакль(новый);
    }

    public synchronized void удалитьСпектакль(long id) {
        получитьСпектакль(id);
        for (Показ показ : репозиторий.всеПоказы()) {
            if (показ.idСпектакля == id) {
                throw ошибка(HttpStatus.CONFLICT, "Сначала удалите показы этого спектакля.");
            }
        }
        репозиторий.удалитьСпектакль(id);
    }

    // Залы

    public synchronized List<Зал> получитьЗалы() {
        return репозиторий.всеЗалы();
    }

    public synchronized Зал получитьЗал(long id) {
        Зал зал = репозиторий.найтиЗал(id);
        if (зал == null) {
            throw ошибка(HttpStatus.NOT_FOUND, "Зал не найден.");
        }
        return зал;
    }

    public synchronized Зал создатьЗал(Зал зал) {
        проверитьЗал(зал);
        зал.id = null;
        return репозиторий.сохранитьЗал(зал);
    }

    public synchronized Зал изменитьЗал(long id, Зал изменения) {
        Зал прежний = получитьЗал(id);
        Зал новый = new Зал();
        новый.id = id;
        новый.название = изменения.название != null ? изменения.название : прежний.название;
        новый.числоМест = изменения.числоМест != null ? изменения.числоМест : прежний.числоМест;
        проверитьЗал(новый);

        for (Показ показ : репозиторий.всеПоказы()) {
            if (показ.idЗала == id) {
                проверитьМестаБилетов(показ.id, новый.числоМест);
            }
        }
        return репозиторий.сохранитьЗал(новый);
    }

    public synchronized void удалитьЗал(long id) {
        получитьЗал(id);
        for (Показ показ : репозиторий.всеПоказы()) {
            if (показ.idЗала == id) {
                throw ошибка(HttpStatus.CONFLICT, "Сначала удалите показы в этом зале.");
            }
        }
        репозиторий.удалитьЗал(id);
    }

    // Показы

    public synchronized List<Показ> получитьПоказы() {
        return репозиторий.всеПоказы();
    }

    public synchronized Показ получитьПоказ(long id) {
        Показ показ = репозиторий.найтиПоказ(id);
        if (показ == null) {
            throw ошибка(HttpStatus.NOT_FOUND, "Показ не найден.");
        }
        return показ;
    }

    public synchronized Показ создатьПоказ(Показ показ) {
        if (показ.статус == null) {
            показ.статус = "ЗАПЛАНИРОВАН";
        }
        проверитьПоказ(показ);
        показ.id = null;
        return репозиторий.сохранитьПоказ(показ);
    }

    public synchronized Показ изменитьПоказ(long id, Показ изменения) {
        Показ прежний = получитьПоказ(id);
        Показ новый = new Показ();
        новый.id = id;
        новый.idСпектакля = изменения.idСпектакля != null ? изменения.idСпектакля : прежний.idСпектакля;
        новый.idЗала = изменения.idЗала != null ? изменения.idЗала : прежний.idЗала;
        новый.начало = изменения.начало != null ? изменения.начало : прежний.начало;
        новый.базоваяЦена = изменения.базоваяЦена != null ? изменения.базоваяЦена : прежний.базоваяЦена;
        новый.статус = изменения.статус != null ? изменения.статус : прежний.статус;
        проверитьПоказ(новый);
        Зал зал = получитьЗал(новый.idЗала);
        проверитьМестаБилетов(id, зал.числоМест);
        return репозиторий.сохранитьПоказ(новый);
    }

    public synchronized void удалитьПоказ(long id) {
        получитьПоказ(id);
        for (Билет билет : репозиторий.всеБилеты()) {
            if (билет.idПоказа == id) {
                throw ошибка(HttpStatus.CONFLICT, "Сначала удалите билеты на этот показ.");
            }
        }
        репозиторий.удалитьПоказ(id);
    }

    // Пользователи

    public synchronized List<Пользователь> получитьПользователей() {
        return репозиторий.всеПользователи();
    }

    public synchronized Пользователь получитьПользователя(long id) {
        Пользователь пользователь = репозиторий.найтиПользователя(id);
        if (пользователь == null) {
            throw ошибка(HttpStatus.NOT_FOUND, "Пользователь не найден.");
        }
        return пользователь;
    }

    public synchronized Пользователь создатьПользователя(Пользователь пользователь) {
        проверитьИмя(пользователь.имя, "Укажите имя пользователя.");
        пользователь.id = null;
        return репозиторий.сохранитьПользователя(пользователь);
    }

    public synchronized Пользователь изменитьПользователя(long id, Пользователь изменения) {
        Пользователь прежний = получитьПользователя(id);
        Пользователь новый = new Пользователь();
        новый.id = id;
        новый.имя = изменения.имя != null ? изменения.имя : прежний.имя;
        проверитьИмя(новый.имя, "Укажите имя пользователя.");
        return репозиторий.сохранитьПользователя(новый);
    }

    public synchronized void удалитьПользователя(long id) {
        получитьПользователя(id);
        for (Билет билет : репозиторий.всеБилеты()) {
            if (билет.idПользователя == id) {
                throw ошибка(HttpStatus.CONFLICT, "Сначала удалите билеты этого пользователя.");
            }
        }
        репозиторий.удалитьПользователя(id);
    }

    // Билеты

    public synchronized List<Билет> получитьБилеты() {
        return репозиторий.всеБилеты();
    }

    public synchronized Билет получитьБилет(long id) {
        Билет билет = репозиторий.найтиБилет(id);
        if (билет == null) {
            throw ошибка(HttpStatus.NOT_FOUND, "Билет не найден.");
        }
        return билет;
    }

    public synchronized Билет создатьБилет(Билет билет) {
        билет.id = null;
        if (билет.статус == null) {
            билет.статус = "БРОНЬ";
        }
        проверитьБилет(билет);
        return репозиторий.сохранитьБилет(билет);
    }

    public synchronized Билет изменитьБилет(long id, Билет изменения) {
        Билет прежний = получитьБилет(id);
        Билет новый = new Билет();
        новый.id = id;
        новый.idПоказа = изменения.idПоказа != null ? изменения.idПоказа : прежний.idПоказа;
        новый.номерМеста = изменения.номерМеста != null ? изменения.номерМеста : прежний.номерМеста;
        новый.idПользователя = изменения.idПользователя != null
                ? изменения.idПользователя : прежний.idПользователя;
        новый.статус = изменения.статус != null ? изменения.статус : прежний.статус;
        проверитьБилет(новый);
        return репозиторий.сохранитьБилет(новый);
    }

    public synchronized void удалитьБилет(long id) {
        получитьБилет(id);
        репозиторий.удалитьБилет(id);
    }

    // Проверки данных

    private void проверитьСпектакль(Спектакль спектакль) {
        проверитьИмя(спектакль.название, "Укажите название спектакля.");
        if (спектакль.длительностьМинут == null || спектакль.длительностьМинут <= 0) {
            throw ошибка(HttpStatus.BAD_REQUEST, "Длительность спектакля должна быть больше нуля.");
        }
        if (спектакль.возрастноеОграничение == null || спектакль.возрастноеОграничение < 0) {
            throw ошибка(HttpStatus.BAD_REQUEST, "Возрастное ограничение должно быть неотрицательным.");
        }
    }

    private void проверитьЗал(Зал зал) {
        проверитьИмя(зал.название, "Укажите название зала.");
        if (зал.числоМест == null || зал.числоМест <= 0) {
            throw ошибка(HttpStatus.BAD_REQUEST, "Число мест должно быть больше нуля.");
        }
    }

    private void проверитьПоказ(Показ показ) {
        if (показ.idСпектакля == null || показ.idЗала == null || показ.начало == null) {
            throw ошибка(HttpStatus.BAD_REQUEST, "Для показа укажите idСпектакля, idЗала и начало.");
        }
        if (показ.базоваяЦена == null || показ.базоваяЦена.signum() < 0) {
            throw ошибка(HttpStatus.BAD_REQUEST, "Базовая цена должна быть неотрицательной.");
        }
        if (!"ЗАПЛАНИРОВАН".equals(показ.статус) && !"ОТМЕНЁН".equals(показ.статус)
                && !"ЗАВЕРШЁН".equals(показ.статус)) {
            throw ошибка(HttpStatus.BAD_REQUEST, "Статус показа: ЗАПЛАНИРОВАН, ОТМЕНЁН или ЗАВЕРШЁН.");
        }
        получитьСпектакль(показ.idСпектакля);
        получитьЗал(показ.idЗала);
    }

    private void проверитьБилет(Билет билет) {
        if (билет.idПоказа == null || билет.idПользователя == null || билет.номерМеста == null) {
            throw ошибка(HttpStatus.BAD_REQUEST, "Для билета укажите idПоказа, idПользователя и номерМеста.");
        }
        if (!"БРОНЬ".equals(билет.статус) && !"КУПЛЕН".equals(билет.статус)) {
            throw ошибка(HttpStatus.BAD_REQUEST, "Статус билета: БРОНЬ или КУПЛЕН.");
        }
        Показ показ = получитьПоказ(билет.idПоказа);
        получитьПользователя(билет.idПользователя);
        Зал зал = получитьЗал(показ.idЗала);
        if (билет.номерМеста < 1 || билет.номерМеста > зал.числоМест) {
            throw ошибка(HttpStatus.BAD_REQUEST, "Номер места должен быть от 1 до " + зал.числоМест + ".");
        }

        // Текущее время берётся на сервере, а из запроса приходит только начало показа.
        if (!"ЗАПЛАНИРОВАН".equals(показ.статус) || !показ.начало.isAfter(LocalDateTime.now())) {
            throw ошибка(HttpStatus.CONFLICT, "Билеты доступны только на будущий запланированный показ.");
        }
        for (Билет существующий : репозиторий.всеБилеты()) {
            if (существующий.idПоказа.equals(билет.idПоказа)
                    && существующий.номерМеста.equals(билет.номерМеста)
                    && !существующий.id.equals(билет.id)) {
                throw ошибка(HttpStatus.CONFLICT, "Это место уже забронировано или куплено.");
            }
        }
    }

    private void проверитьМестаБилетов(long idПоказа, int числоМест) {
        for (Билет билет : репозиторий.всеБилеты()) {
            if (билет.idПоказа == idПоказа && билет.номерМеста > числоМест) {
                throw ошибка(HttpStatus.CONFLICT, "В этом зале нет места, указанного в существующем билете.");
            }
        }
    }

    private void проверитьИмя(String имя, String сообщение) {
        if (имя == null || имя.isBlank()) {
            throw ошибка(HttpStatus.BAD_REQUEST, сообщение);
        }
    }

    private ResponseStatusException ошибка(HttpStatus статус, String сообщение) {
        return new ResponseStatusException(статус, сообщение);
    }
}
